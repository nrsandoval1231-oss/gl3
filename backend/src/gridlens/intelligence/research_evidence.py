# This is a conservative admission exclusion, not a lifecycle/supply classifier.
# Mixed relationship and adverse-power pages need normal activity interpretation;
# they cannot gain acceptance through the narrower contact-only exception.
_RELATIONSHIP_CONFLICT = re.compile(
    r"\b(?:cancel(?:led|ed|lation)?|halt(?:ed)?|paused?|suspend(?:ed)?|"
    r"withdraw(?:n|al)?|denied|abandon(?:ed)?|shelved|completed?|closed|"
    r"energiz(?:ed|ation)|adequate|sufficient|secured|operational|"
    r"no longer|not proceeding|not required|not needed)\b|"
    r"\b(?:permanent|utility|grid) (?:power|service|supply|connection)\b",
    re.I,
)
_HARD_ADVERSE = re.compile(
    r"\b(?:cancel(?:led|ed|lation)?|halt(?:ed)?|paused?|suspend(?:ed)?|"
    r"withdraw(?:n|al)?|denied|abandon(?:ed)?|shelved|completed?|closed|"
    r"energiz(?:ed|ation)|adequate|sufficient|secured|operational|"
    r"no longer|not proceeding|not required|not needed)\b",
    re.I,
)
_UNTRUSTED_SUMMARY = re.compile(
    r"\b(?:AI[- ]generated|AI[- ]summary|generated by (?:AI|ChatGPT)|"
    r"search engine optimization|SEO directory|business directory|company directory)\b",
    re.I,
)
_CONTACT_ONLY_REJECTIONS = {
    "The retained text does not establish a physical facility and a concrete project action.",
    "The retained text does not establish a qualifying physical project action.",
}


def _relationship_publisher_matches(document: PublicDocument, organizations: list) -> bool:
    """Require the relationship publisher to be the explicitly named organization.

    Keep the existing official-profile exact host/name discipline. Unknown hosts,
    directories and syndicators cannot bootstrap canonical project relationships.
    This intentionally excludes aliases and contractor claims on unverified owner pages.
    """
    host = (urlsplit(document.url).hostname or "").removeprefix("www.")
    labels = host.split(".")
    if len(labels) != 2 or labels[1] not in {"com", "org", "net"}:
        return False
    title = organization_key(document.title)
    return any(
        labels[0] == re.sub(r"[^a-z0-9]", "", organization_key(item.organization))
        and re.search(
            r"(?<!\w)" + re.escape(organization_key(item.organization)) + r"(?!\w)", title
        )
        for item in organizations
    )


def _publisher_eligible(document: PublicDocument, project: Project) -> bool:
    host = (urlsplit(document.url).hostname or "").removeprefix("www.")
    reviewed = {
        (urlsplit(source["endpoint"]).hostname or "").removeprefix("www.")
        for source in load_registry()
        if source.get("retrieval_method") == "publisher-rss" and source.get("family") == "news"
    }
    return host in reviewed or _relationship_publisher_matches(
        document,
        [
            item
            for item in extract_organizations(document, project)
            if item.organization_relationship == "DIRECT"
        ],
    )


def _retained_excerpt(document: PublicDocument) -> PublicDocument:
    # Keep the reason for exclusion inspectable even when it occurs after the
    # usual context bound. Neither truncation nor hashing may hide a correction.
    full_text = document.title + "\n" + document.text
    excluded = (
        _UNTRUSTED_SUMMARY.search(full_text)
        or _HARD_ADVERSE.search(full_text)
        or _RELATIONSHIP_CONFLICT.search(full_text)
    )
    excerpt = document.text[:4000]
    if excluded and excluded.end() > 400:
        start = max(0, excluded.start() - 120)
        quote = full_text[start : excluded.end() + 240]
        excerpt = (quote + "\n[Earlier page context]\n" + document.text[:3400])[:4000]
    return replace(document, text=excerpt, title=document.title[:500])


def _quarantine_existing_public(
    session: Session,
    project: Project,
    need: PowerNeed,
    document: PublicDocument,
    receipt: dict,
    reason: str,
) -> dict:
    """Retract current same-URL support through normal canonical rejection.

    New untrusted pages remain receipts only. Previously retained observations
    get an immutable rejected version and normal support/lifecycle cleanup.
    """
    url = validate_public_url(document.url)
    observations = list(
        session.scalars(
            select(Observation)
            .join(Source, Source.id == Observation.source_id)
            .join(NeedObservation, NeedObservation.observation_id == Observation.id)
            .where(
                Observation.url == url, Source.family == "news", NeedObservation.need_id == need.id
            )
            .order_by(Observation.id)
            .with_for_update(of=Observation)
        )
    )
    result = {**receipt, "disposition": "QUARANTINED", "reason": reason}
    ids = []
    for observation in observations:
        current = _quarantine_public_observation(
            session, project, need, observation, document, receipt, reason
        )
        if current.get("current_support_invalidated"):
            result = current
            ids.extend(current["evidence_ids"])
    return {**result, "evidence_ids": ids}


def _quarantine_public_observation(
    session: Session,
    project: Project,
    need: PowerNeed,
    observation: Observation,
    document: PublicDocument,
    receipt: dict,
    reason: str,
) -> dict:
    url = validate_public_url(document.url)
    result = {**receipt, "disposition": "QUARANTINED", "reason": reason}
    targets = list(
        session.scalars(
            select(NeedObservation.need_id).where(NeedObservation.observation_id == observation.id)
        )
    )
    if targets != [need.id]:
        return result
    interpretation = session.scalar(
        select(Interpretation).where(Interpretation.observation_id == observation.id)
    )
    if interpretation is None:
        return result
    assessment = interpretation.assessment or {}
    identities = {
        assessment.get("project_identity_key"),
        assessment.get("superseded_project_identity_key"),
    }
    if project.identity_key not in identities:
        return result
    digest = fingerprint([document.title, document.text, document.published_at])
    bounded = _retained_excerpt(document)
    evidence = session.scalar(
        select(Evidence).where(
            Evidence.observation_id == observation.id, Evidence.content_hash == digest
        )
    )
    duplicate = evidence is not None
    if evidence is None:
        evidence = Evidence(
            observation_id=observation.id,
            content_hash=digest,
            title=bounded.title,
            abstract=bounded.text,
            url=url,
            published_at=document.published_at,
            observed_at=document.observed_at,
            extraction_location=document.extraction_location[:100],
        )
        session.add(evidence)
        session.flush()
    if not (
        interpretation.status == "rejected"
        and observation.content_hash == digest
        and assessment.get("admission_status") == "research_quarantine"
    ):
        observation.title, observation.abstract = bounded.title, bounded.text
        observation.content_hash, observation.published_at = digest, document.published_at
        assess_retained_news(session, observation, evidence, rejection_reason=reason)
        session.flush()
        _apply_current_qualification(session, need, project)
    return {
        **result,
        "evidence_id": str(evidence.id),
        "evidence_ids": [str(evidence.id)],
        "excerpt": bounded.text,
        "duplicate": duplicate,
        "current_support_invalidated": True,
    }


def _receipt(document: PublicDocument, publisher: str) -> dict:
    return {
        "url": document.url,
        "publisher": publisher,
        "retrieved_at": document.observed_at.isoformat(),
        "published_at": document.published_at.isoformat() if document.published_at else None,
        "excerpt": _retained_excerpt(document).text,
        "extraction_location": document.extraction_location,
        "claim_type": "project_activity",
        "evidence_id": None,
        "evidence_ids": [],
        "label": "Unknown",
    }


def retain_registered_record(
    session: Session,
    project: Project,
    need: PowerNeed,
    source_definition: dict[str, Any],
    record: dict[str, Any],
    *,
    job_id: Any,
    worker_id: str,
    fence: int,
) -> dict:
    """Run a refreshed official permit through canonical ingestion atomically.

    Only an already linked stable observation may be refreshed. If canonical
    admission identifies another target, every mutation is rolled back and the
    bounded rejected excerpt remains solely in the caller's research receipt.
    """
    source_id = source_definition.get("id")
    if source_id not in SUPPORTED_SOURCES or source_definition not in load_registry():
        raise ValueError("Research requires the unchanged registered source definition")
    document = PublicDocument(
        url=validate_public_url(record["html_url"]),
        title=record["title"],
        text=record.get("abstract") or "",
        published_at=date.fromisoformat(record["publication_date"]),
        extraction_location=record["extraction_location"],
    )
    receipt = _receipt(document, source_definition["publisher"])
    observation = session.scalar(
        select(Observation)
        .where(
            Observation.source_id == source_id,
            Observation.external_id == record["document_number"],
        )
        .with_for_update()
    )
    if (
        observation is None
        or session.scalar(
            select(NeedObservation.id).where(
                NeedObservation.observation_id == observation.id,
                NeedObservation.need_id == need.id,
            )
        )
        is None
        or need.project_id != project.id
    ):
        return {**receipt, "disposition": "QUARANTINED", "reason": "unbound_stable_record"}
    prior_ids = set(
        session.scalars(select(Evidence.id).where(Evidence.observation_id == observation.id))
    )
    with session.begin_nested() as admission:
        counts = process_records(
            session,
            job_id,
            worker_id,
            fence,
            source_definition,
            [record],
            commit=False,
            allow_model=False,
        )
        targets = list(
            session.scalars(
                select(NeedObservation.need_id).where(
                    NeedObservation.observation_id == observation.id
                )
            )
        )
        interpretation = session.scalar(
            select(Interpretation).where(Interpretation.observation_id == observation.id)
        )
        assessment = interpretation.assessment if interpretation else {}
        if any(target != need.id for target in targets) or (
            assessment
            and assessment.get("project_identity_key") not in (None, project.identity_key)
        ):
            admission.rollback()
            return {
                **receipt,
                "disposition": "QUARANTINED",
                "reason": "existing_admission_did_not_match_exact_target",
            }
        evidence = session.scalar(
            select(Evidence).where(
                Evidence.observation_id == observation.id,
                Evidence.content_hash == record["source_hash"],
            )
        )
        accepted = bool(
            interpretation and interpretation.status == "accepted" and need.id in targets
        )
        # Normal ingestion also admits source corrections which withdraw an
        # existing activity's support. A rejected qualification is not a failed
        # parse, nor does it mean that the retrieved source fact was rejected.
        support_withdrawn = bool(
            interpretation
            and interpretation.status == "rejected"
            and assessment
            and assessment.get("stable_row_id") == record["document_number"]
            and assessment.get("project_identity_key") == project.identity_key
            and not need.active
            and evidence is not None
        )
        accepted = accepted or support_withdrawn
        return {
            **receipt,
            "disposition": "ACCEPTED" if accepted else "UNRESOLVED",
            "reason": str(
                (assessment or {}).get("reason") or "No admissible project activity claim"
            ),
            "evidence_id": str(evidence.id) if evidence else None,
            "evidence_ids": [str(evidence.id)] if evidence else [],
            "duplicate": evidence is not None and evidence.id in prior_ids,
            "label": "Verified" if accepted else "Unknown",
            "match_basis": "Existing canonical source and stable record identity",
            "ingestion_counts": counts,
            "canonical_support_withdrawn": support_withdrawn,
        }


class _PublicTargetMismatch(Exception):
    """Rollback tentative admission before rejecting this URL's prior support."""


def _current_semantic_evidence(
    session: Session, project: Project, need: PowerNeed, evidence: Evidence
) -> bool:
    from gridlens.intelligence.project_state import current_research_state

    fields = current_research_state(session, project.id, need.id).get(str(need.id), {})
    return any(
        claim.get("evidence_id") == str(evidence.id)
        for field in fields.values()
        for claim in field.get("claims", [])
    )


def _current_duplicate_document(
    session: Session,
    project: Project,
    need: PowerNeed,
    digest: str,
) -> Evidence | None:
    from gridlens.intelligence.buying_chain import _retained_evidence_current_for_project

    if not need.active:
        return None
    candidates = session.scalars(
        select(Evidence)
        .join(Observation, Observation.id == Evidence.observation_id)
        .join(NeedObservation, NeedObservation.observation_id == Observation.id)
        .join(Interpretation, Interpretation.observation_id == Observation.id)
        .where(
            NeedObservation.need_id == need.id,
            Evidence.content_hash == digest,
            Observation.content_hash == digest,
            Interpretation.content_hash == digest,
            Interpretation.status == "accepted",
            Interpretation.assessment["evidence_hash"].astext == digest,
            Interpretation.assessment["project_identity_key"].astext == project.identity_key,
        )
        .order_by(Evidence.observed_at, Evidence.id)
    )
    return next(
        (
            evidence
            for evidence in candidates
            if _retained_evidence_current_for_project(session, project, evidence)
            or _current_semantic_evidence(session, project, need, evidence)
        ),
        None,
    )


def retain_research_document(
    session: Session,
    project: Project,
    need: PowerNeed,
    document: PublicDocument,
) -> dict:
    if need.project_id != project.id:
        raise ValueError("PowerNeed does not belong to selected project")
    url = validate_public_url(document.url)
    receipt = _receipt(document, str(urlsplit(url).hostname))
    if document.structured:
        return _quarantine_existing_public(
            session, project, need, document, receipt, "use_registered_record_adapter"
        )
    if _UNTRUSTED_SUMMARY.search(document.title + "\n" + document.text):
        # A concrete event-shaped claim does not override an explicitly weak
        # source. Keep only the bounded quarantine receipt, never canonical claims.
        return _quarantine_existing_public(
            session,
            project,
            need,
            document,
            receipt,
            "Declared generated summary or directory is not admissible evidence",
        )
    if not _publisher_eligible(document, project):
        return _quarantine_existing_public(
            session,
            project,
            need,
            document,
            receipt,
            "Public publisher is neither reviewed nor the exact project organization",
        )
    semantic_claims = extract_project_claims(
        document.text,
        references=[project.name, project.location or ""],
        activity_key=need.activity_key,
        published_at=document.published_at,
        today=date.today(),
    )
    # Every adverse clause must be understood; a positive elsewhere never masks
    # an unparsed negative. Supported explicit negatives are typed reports.
    uncovered = unparsed_adverse_text(document.text, semantic_claims)
    # A headline may repeat a supported report in abbreviated form. It may not
    # introduce another negative that the dated exact-project body never supports.
    title_remainder = document.title
    title_patterns = {
        ("phase", "cancelled"): r"\bcancel(?:led|ed|lation)\b",
        ("phase", "completed"): r"\bcompleted?\b",
        ("phase", "paused"): r"\b(?:paused?|suspended)\b",
        ("permanent_service", "energized"): r"\benergiz(?:ed|ation)\b",
        ("supply_adequacy", "adequate"): r"\b(?:adequate|sufficient)\b",
    }
    for claim in semantic_claims:
        pattern = title_patterns.get((claim["field"], claim["value"]))
        if pattern:
            title_remainder = re.sub(pattern, "", title_remainder, flags=re.I)
    if _HARD_ADVERSE.search(title_remainder + "\n" + uncovered):
        return _quarantine_existing_public(
            session,
            project,
            need,
            document,
            receipt,
            "Adverse claim lacks exact-project dated semantic support",
        )
    matched, basis = project_document_match(project, document)
    if not matched:
        return _quarantine_existing_public(session, project, need, document, receipt, basis)
    relationship_excluded = bool(
        _RELATIONSHIP_CONFLICT.search(document.title + "\n" + document.text)
        or _UNTRUSTED_SUMMARY.search(document.title + "\n" + document.text)
    )
    # Fingerprint the entire bounded retrieval, including text outside the retained
    # excerpt. The excerpt keeps exclusion text first so normal rejection sees it.
    digest = fingerprint([document.title, document.text, document.published_at])
    original_document = document
    if semantic_claims:
        excerpt = "\n".join(dict.fromkeys(claim["quote"] for claim in semantic_claims))
        if len(excerpt) > 4000:
            return _quarantine_existing_public(
                session, project, need, document, receipt, "semantic_claim_retention_budget"
            )
        if len(document.text) <= 4000:
            excerpt = document.text
        else:
            context = document.text[: min(600, 3999 - len(excerpt))]
            excerpt = context + "\n" + excerpt
        document = replace(document, text=excerpt)
    else:
        document = _retained_excerpt(document)
    matched, basis = project_document_match(project, document)
    if not matched:
        return _quarantine_existing_public(
            session, project, need, original_document, receipt, "identity_outside_retention_bound"
        )
    # Different URLs can return the identical document. Serialize their admission
    # by exact target+full-content hash without waiting past the research deadline.
    acquired = session.scalar(
        text("SELECT pg_try_advisory_xact_lock(hashtextextended(:key, 30))"),
        {"key": fingerprint([need.id, digest])},
    )
    if not acquired:
        return {
            **receipt,
            "disposition": "UNRESOLVED",
            "reason": "Identical document admission is in progress; no waiting or duplicate write",
        }
    # Reuse is safe only for a newly encountered URL. A known URL may be
    # correcting its own prior accepted claims; it must append a version and
    # replace that interpretation even when another URL already has these bytes.
    known_url = session.scalar(select(Observation.id).where(Observation.url == url).limit(1))
    existing = (
        _current_duplicate_document(session, project, need, digest) if known_url is None else None
    )
    if existing is not None:
        existing_interpretation = session.scalar(
            select(Interpretation).where(Interpretation.observation_id == existing.observation_id)
        )
        existing_assessment = existing_interpretation.assessment if existing_interpretation else {}
        return {
            **receipt,
            "disposition": "ACCEPTED",
            "duplicate": True,
            "reason": "Identical document already has current accepted evidence for this need",
            "evidence_id": str(existing.id),
            "evidence_ids": [str(existing.id)],
            "evidence_url": existing.url,
            "research_claims": (existing_assessment or {}).get("research_claims", []),
            "claim_type": "project_research_report"
            if (existing_assessment or {}).get("admission_status") == "project_research_supplement"
            else "project_organization_relationship"
            if (existing_assessment or {}).get("admission_status") == "relationship_supplement"
            else "project_activity",
            "label": "Reported",
            "match_basis": basis,
        }
    try:
        with session.begin_nested():
            host = urlsplit(url).hostname
            source_id = "research-public-" + fingerprint(host)[:32]
            source = session.get(Source, source_id)
            if source is None:
                # A captured public page is supplemental context, never a registered
                # official permit/utility feed. It cannot admit a standalone Signal.
                source = Source(
                    id=source_id,
                    publisher=str(host),
                    endpoint=f"https://{host}/",
                    family="news",
                    geography="Project-scoped public context",
                    industries=[],
                    retrieval_method="publisher-rss",
                    enabled=False,
                    cadence_hours=168,
                    health={"status": "Research context", "scheduled": False},
                )
                session.add(source)
                session.flush()
            external_id = fingerprint(url)
            observation = session.scalar(
                select(Observation)
                .where(Observation.source_id == source_id, Observation.external_id == external_id)
                .with_for_update()
            )
            if observation is None:
                observation = Observation(
                    source_id=source_id,
                    external_id=external_id,
                    title=document.title,
                    abstract=document.text,
                    url=url,
                    published_at=document.published_at,
                    content_hash=digest,
                )
                session.add(observation)
                session.flush()
            evidence = session.scalar(
                select(Evidence).where(
                    Evidence.observation_id == observation.id, Evidence.content_hash == digest
                )
            )
            duplicate = evidence is not None
            if evidence is None:
                evidence = Evidence(
                    observation_id=observation.id,
                    content_hash=digest,
                    title=document.title,
                    abstract=document.text,
                    url=url,
                    published_at=document.published_at,
                    observed_at=document.observed_at,
                    extraction_location=document.extraction_location[:100],
                )
                session.add(evidence)
                session.flush()
            observation.title, observation.abstract = document.title, document.text
            observation.content_hash, observation.published_at = digest, document.published_at
            # The existing evaluator owns all qualification, linking, and state projection.
            # A targeted attempt is not authorization to modify another physical project.
            previous = session.scalar(
                select(Interpretation).where(Interpretation.observation_id == observation.id)
            )
            relationship_replay = bool(
                not relationship_excluded
                and previous
                and previous.status == "accepted"
                and previous.content_hash == digest
                and (previous.assessment or {}).get("evidence_hash") == evidence.content_hash
                and (previous.assessment or {}).get("admission_status") == "relationship_supplement"
                and previous.evaluator_version == "research-relationship-v2"
            )
            semantic_replay = bool(
                semantic_claims
                and previous
                and previous.status == "accepted"
                and previous.content_hash == digest
                and previous.evaluator_version == VERSION
                and (previous.assessment or {}).get("evidence_hash") == digest
                and (previous.assessment or {}).get("target_need_id") == str(need.id)
            )
            if semantic_claims and not semantic_replay:
                # Normal rejection cleanup retracts the previous whole-document
                # interpretation before narrowly admitting only typed reports.
                assess_retained_news(
                    session,
                    observation,
                    evidence,
                    rejection_reason="Replaced by scoped reported project research claims",
                )
            elif not semantic_replay and not relationship_replay:
                assess_retained_news(session, observation, evidence)
            targets = list(
                session.scalars(
                    select(NeedObservation.need_id).where(
                        NeedObservation.observation_id == observation.id
                    )
                )
            )
            interpretation = session.scalar(
                select(Interpretation).where(Interpretation.observation_id == observation.id)
            )
            assessment = interpretation.assessment if interpretation else {}
            if any(target != need.id for target in targets) or (
                assessment
                and assessment.get("project_identity_key") not in (None, project.identity_key)
            ):
                raise _PublicTargetMismatch()
            if (
                semantic_claims
                and interpretation is not None
                and not semantic_replay
                and _need_admission_basis_is_current(session, need, project)
            ):
                history = list((assessment or {}).get("previous_decisions", []))
                history.append(
                    {k: v for k, v in (assessment or {}).items() if k != "previous_decisions"}
                )
                interpretation.status = "accepted"
                interpretation.error = None
                interpretation.evaluator_version = VERSION
                interpretation.assessment = {
                    "decision": "accepted",
                    "admission_status": "project_research_supplement",
                    "project_identity_key": project.identity_key,
                    "target_need_id": str(need.id),
                    "semantic_hash": digest,
                    "evidence_hash": digest,
                    "reason": "Explicit dated project reports; no public tier qualification",
                    "research_claims": [
                        {
                            **claim,
                            "project_id": str(project.id),
                            "need_id": str(need.id),
                            "evidence_id": str(evidence.id),
                            "evidence_hash": digest,
                        }
                        for claim in semantic_claims
                    ],
                    "previous_decisions": history,
                }
                if need.id not in targets:
                    session.add(NeedObservation(observation_id=observation.id, need_id=need.id))
                    targets.append(need.id)
                session.flush()
                _apply_current_qualification(session, need, project)
            relationship_quarantined = False
            if (
                interpretation is not None
                and interpretation.status == "rejected"
                and need.active
                and _need_admission_basis_is_current(session, need, project)
            ):
                organizations = [
                    item
                    for item in extract_organizations(document, project)
                    if item.organization_relationship == "DIRECT"
                ]
                relationship_quarantined = bool(organizations) and (
                    relationship_excluded
                    or (assessment or {}).get("reason") not in _CONTACT_ONLY_REJECTIONS
                    or not _relationship_publisher_matches(document, organizations)
                )
                if organizations and not relationship_quarantined:
                    # This is an explicit relationship supplement, not acceptance
                    # of every sentence on the page as activity or power evidence.
                    # Existing buying-chain extraction owns person and role semantics.
                    history = list((assessment or {}).get("previous_decisions", []))
                    history.append(
                        {
                            key: value
                            for key, value in (assessment or {}).items()
                            if key != "previous_decisions"
                        }
                    )
                    interpretation.status = "accepted"
                    interpretation.error = None
                    interpretation.evaluator_version = "research-relationship-v2"
                    interpretation.assessment = {
                        "decision": "accepted",
                        "admission_status": "relationship_supplement",
                        "project_identity_key": project.identity_key,
                        "semantic_hash": digest,
                        "evidence_hash": evidence.content_hash,
                        "reason": "Explicit project organization role; buying authority unknown.",
                        "relationship_claims": [
                            {
                                "organization": item.organization,
                                "category": item.category,
                                "citations": item.citations,
                            }
                            for item in organizations
                        ],
                        "previous_decisions": history,
                    }
                    if need.id not in targets:
                        session.add(NeedObservation(observation_id=observation.id, need_id=need.id))
                        targets.append(need.id)
                    session.flush()
    except _PublicTargetMismatch:
        return _quarantine_existing_public(
            session,
            project,
            need,
            original_document,
            receipt,
            "existing_admission_did_not_match_exact_target",
        )

    interpretation = session.scalar(
        select(Interpretation).where(Interpretation.observation_id == observation.id)
    )
    assessment = interpretation.assessment if interpretation else {}
    accepted = bool(
        interpretation
        and interpretation.status == "accepted"
        and assessment
        and assessment.get("project_identity_key") == project.identity_key
        and need.id in targets
    )
    return {
        **receipt,
        "evidence_id": str(evidence.id),
        "evidence_ids": [str(evidence.id)],
        "disposition": "ACCEPTED"
        if accepted
        else "QUARANTINED"
        if relationship_quarantined
        else "UNRESOLVED",
        "reason": (
            "Relationship page is mixed, adverse, or lacks an authoritative organization publisher"
            if relationship_quarantined
            else str((assessment or {}).get("reason") or "No admissible project activity claim")
        ),
        "match_basis": basis,
        "duplicate": duplicate,
        "label": "Reported" if accepted else "Unknown",
        "research_claims": (assessment or {}).get("research_claims", []),
        "claim_type": "project_research_report"
        if (assessment or {}).get("admission_status") == "project_research_supplement"
        else "project_organization_relationship"
        if (assessment or {}).get("admission_status") == "relationship_supplement"
        else "project_activity",
    }
