"""Gold-set gates for permit-document extraction.

The gold set is hand-labelled (see fixtures/permit_docs/gold/README.md); expectations are never
generated by running the parser. Two gates:

1. Field precision over the fields the extractor ASSERTS (type, rating and unit always; count,
   drive and state only when it states one), each field scored independently, at least 0.98,
   with any wrong drive failing outright. A missing optional value is a recall miss.
2. A zero-tolerance gate on ``result.claims`` (the rows that feed demand): every claim must
   match one expected row on type, drive, rating, unit, state (when labelled) and count (when
   the claim states one), and no claim may be left over.

Rows are matched to expected rows by id, then by type and rating, then by type and document
order (so a wrong rating or unit is scored as an error instead of an "unexpected row").
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from decimal import Decimal
from pathlib import Path

import pytest

from gridlens.ingestion.parsers.permit_docs import PermitExtractionResult, extract_from_pages
from gridlens.ingestion.parsers.permit_docs.models import ExtractedRow

GOLD_DIR = Path(__file__).resolve().parents[1] / "fixtures" / "permit_docs" / "gold"
PRECISION_GATE = 0.98
RECALL_FLOOR = 0.45  # informational baseline; guards against silent regressions
MIN_DOCUMENTS = 35


@dataclass(slots=True)
class Score:
    asserted: int = 0
    correct: int = 0
    wrong_drives: list[str] = field(default_factory=list)
    errors: list[str] = field(default_factory=list)
    expected_fields: int = 0
    recalled_fields: int = 0
    expected_rows: int = 0
    matched_rows: int = 0
    extracted_rows: int = 0
    unmatched_rows: int = 0
    claim_errors: list[str] = field(default_factory=list)
    claims: int = 0


def load_gold() -> list[dict]:
    entries: list[dict] = []
    for path in sorted(GOLD_DIR.glob("*.jsonl")):
        for line in path.read_text(encoding="utf-8").splitlines():
            if line.strip():
                entries.append(json.loads(line))
    return entries


def _row_fields(row: ExtractedRow) -> dict[str, object]:
    fields: dict[str, object] = {
        "type": row.equipment_type,
        "rating": row.rating,
        "unit": row.unit,
    }
    if row.count is not None:
        fields["count"] = row.count
    if row.drive != "unknown":
        fields["drive"] = row.drive
    if row.state != "unknown":
        fields["state"] = row.state
    return fields


def _truth(exp: dict) -> dict[str, object]:
    return {
        "type": exp["type"],
        "rating": Decimal(exp["rating_value"]),
        "unit": exp["unit"],
        "count": exp["count"],
        "drive": exp["drive"],
        "state": exp.get("state"),
    }


def match_rows(rows: list[ExtractedRow], expected: list[dict]) -> dict[int, int]:
    """Map extracted row index -> expected index (id, then type+rating, then type in order)."""
    used: set[int] = set()
    mapping: dict[int, int] = {}

    def take(rule) -> None:  # type: ignore[no-untyped-def]
        for r_index, row in enumerate(rows):
            if r_index in mapping:
                continue
            for e_index, exp in enumerate(expected):
                if e_index not in used and rule(row, exp):
                    mapping[r_index] = e_index
                    used.add(e_index)
                    break

    take(
        lambda r, e: e["equipment_id"] is not None
        and e["equipment_id"] == r.equipment_id
        and e["type"] == r.equipment_type
        and Decimal(e["rating_value"]) == r.rating
    )
    take(
        lambda r, e: e["equipment_id"] is None
        and r.origin == "narrative"
        and e["type"] == r.equipment_type
        and Decimal(e["rating_value"]) == r.rating
        and e["count"] == r.count
    )
    take(
        lambda r, e: (e["equipment_id"] is None) == (r.origin == "narrative")
        and e["type"] == r.equipment_type
        and Decimal(e["rating_value"]) == r.rating
    )
    take(lambda r, e: e["equipment_id"] == r.equipment_id and e["equipment_id"] is not None)
    take(
        lambda r, e: (e["equipment_id"] is None) == (r.origin == "narrative")
        and e["type"] == r.equipment_type
    )
    return mapping


def score_entry(entry: dict, score: Score) -> PermitExtractionResult:
    result = extract_from_pages(
        entry["page_text_excerpt"].split("\f"), document_hash="gold:" + entry["doc_id"]
    )
    rows = result.demand_rows + result.supply_rows
    expected = entry["expected_rows"]
    mapping = match_rows(rows, expected)
    score.expected_rows += len(expected)
    score.extracted_rows += len(rows)
    for r_index, row in enumerate(rows):
        asserted = _row_fields(row)
        if r_index not in mapping:
            score.unmatched_rows += 1
            score.asserted += len(asserted)
            score.errors.append(f"{entry['doc_id']}: unexpected row {row.equipment_id}")
            if "drive" in asserted:
                score.wrong_drives.append(f"{entry['doc_id']}:{row.equipment_id}")
            continue
        score.matched_rows += 1
        truth = _truth(expected[mapping[r_index]])
        for name, value in asserted.items():
            if name == "state" and truth["state"] is None:
                continue  # state is scored only where the gold row labels it
            score.asserted += 1
            if truth[name] == value:
                score.correct += 1
            else:
                score.errors.append(
                    f"{entry['doc_id']}: {row.equipment_id} {name} {value!r} != {truth[name]!r}"
                )
                if name == "drive":
                    score.wrong_drives.append(f"{entry['doc_id']}:{row.equipment_id}")
        for name in ("type", "rating", "unit", "count", "drive"):
            if name in ("count", "drive") and truth[name] in (None, "unknown"):
                continue
            score.expected_fields += 1
            score.recalled_fields += int(_row_fields(row).get(name) == truth[name])
    mapped = set(mapping.values())
    for e_index, exp in enumerate(expected):
        if e_index not in mapped:
            score.expected_fields += sum(
                1
                for name in ("type", "rating_value", "unit", "count", "drive")
                if exp[name] not in (None, "unknown")
            )
    return result


def score_claims(entry: dict, result: PermitExtractionResult, score: Score) -> None:
    expected = entry["expected_rows"]
    used: set[int] = set()
    for claim in result.claims:
        score.claims += 1
        for e_index, exp in enumerate(expected):
            if e_index in used:
                continue
            truth = _truth(exp)
            if (
                truth["type"] == claim.equipment_type
                and truth["drive"] == claim.drive
                and truth["rating"] == claim.rating
                and truth["unit"] == claim.unit
                and (claim.count is None or truth["count"] == claim.count)
                and (truth["state"] is None or truth["state"] == claim.state)
                and (
                    truth["state"] is not None
                    or claim.state in ("unknown", "proposed", "new", "existing")
                )
            ):
                used.add(e_index)
                break
        else:
            score.claim_errors.append(
                f"{entry['doc_id']}: claim {claim.equipment_id} {claim.equipment_type} "
                f"{claim.drive} {claim.rating} {claim.unit} x{claim.count} {claim.state}"
            )


@pytest.fixture(scope="module")
def gold_score() -> Score:
    score = Score()
    for entry in load_gold():
        result = score_entry(entry, score)
        score_claims(entry, result, score)
    return score


def test_gold_set_is_large_enough_and_well_formed() -> None:
    entries = load_gold()
    assert len(entries) >= MIN_DOCUMENTS
    ids = [e["doc_id"] for e in entries]
    assert len(ids) == len(set(ids))
    sources = " ".join(e["source"] for e in entries)
    for marker in ("Oklahoma", "NMED", "TCEQ", "Synthetic"):
        assert marker in sources
    for entry in entries:
        assert len(entry["page_text_excerpt"]) < 3500
        for exp in entry["expected_rows"]:
            assert set(exp) - {"state"} == {
                "equipment_id",
                "type",
                "rating_value",
                "unit",
                "count",
                "drive",
            }
            assert exp["drive"] in {"electric", "gas_engine", "diesel_engine", "steam", "unknown"}
            Decimal(exp["rating_value"])


def test_gold_field_precision(gold_score: Score) -> None:
    precision = gold_score.correct / gold_score.asserted
    print(
        f"\ngold precision {precision:.4f} ({gold_score.correct}/{gold_score.asserted} asserted "
        f"fields; {gold_score.unmatched_rows} unexpected rows)"
    )
    assert gold_score.wrong_drives == [], gold_score.wrong_drives
    assert precision >= PRECISION_GATE, "\n".join(gold_score.errors)


def test_gold_claims_are_exact(gold_score: Score) -> None:
    print(f"\ngold demand claims checked: {gold_score.claims}")
    assert gold_score.claims > 0
    assert gold_score.claim_errors == [], "\n".join(gold_score.claim_errors)


def test_gold_recall_is_reported(gold_score: Score) -> None:
    recall = gold_score.recalled_fields / gold_score.expected_fields
    row_recall = gold_score.matched_rows / gold_score.expected_rows
    print(
        f"\ngold recall (informational): fields {recall:.3f} "
        f"({gold_score.recalled_fields}/{gold_score.expected_fields}), "
        f"rows {row_recall:.3f} ({gold_score.matched_rows}/{gold_score.expected_rows})"
    )
    assert recall >= RECALL_FLOOR
