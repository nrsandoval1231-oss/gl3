"""Gold-set gate for permit-document extraction.

The gold set is hand-labelled from public records (see fixtures/permit_docs/gold/README.md);
expectations are never generated by running the parser. Precision is field-level over the
fields the extractor ASSERTS (type, rating, unit always; count and drive only when it states
one). A missing optional value is a recall miss, a wrong one is a precision error. Any wrong
drive fails the gate outright.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from decimal import Decimal
from pathlib import Path

import pytest

from gridlens.ingestion.parsers.permit_docs import extract_from_pages
from gridlens.ingestion.parsers.permit_docs.models import ExtractedRow

GOLD_DIR = Path(__file__).resolve().parents[1] / "fixtures" / "permit_docs" / "gold"
PRECISION_GATE = 0.98
RECALL_FLOOR = 0.45  # informational baseline; guards against silent regressions
MIN_DOCUMENTS = 30


@dataclass(slots=True)
class Score:
    asserted: int = 0
    correct: int = 0
    wrong_drives: list[str] = field(default_factory=list)
    errors: list[str] = field(default_factory=list)
    expected_fields: int = 0
    recalled_fields: int = 0
    expected_rows: int = 0
    matched_rows: int = 0
    extracted_rows: int = 0
    unmatched_rows: int = 0


def load_gold() -> list[dict]:
    entries: list[dict] = []
    for path in sorted(GOLD_DIR.glob("*.jsonl")):
        for line in path.read_text(encoding="utf-8").splitlines():
            if line.strip():
                entries.append(json.loads(line))
    return entries


def _find_match(row: ExtractedRow, expected: list[dict], used: set[int]) -> int | None:
    best: tuple[int, int] | None = None
    for index, exp in enumerate(expected):
        if index in used:
            continue
        if Decimal(exp["rating_value"]) != row.rating or exp["unit"] != row.unit:
            continue
        if exp["equipment_id"] is not None and exp["equipment_id"] != row.equipment_id:
            continue
        if exp["equipment_id"] is None and row.origin != "narrative":
            continue
        score = (exp["type"] == row.equipment_type) * 2 + (exp["count"] == row.count)
        if best is None or score > best[0]:
            best = (score, index)
    return None if best is None else best[1]


def score_entry(entry: dict, score: Score) -> None:
    result = extract_from_pages(
        entry["page_text_excerpt"].split("\f"), document_hash="gold:" + entry["doc_id"]
    )
    rows = result.demand_rows + result.supply_rows
    # Rows dropped as repeats still count against recall only.
    expected = entry["expected_rows"]
    used: set[int] = set()
    score.expected_rows += len(expected)
    score.extracted_rows += len(rows)
    for row in rows:
        index = _find_match(row, expected, used)
        asserted = {"type": row.equipment_type, "rating": row.rating, "unit": row.unit}
        if row.count is not None:
            asserted["count"] = row.count
        if row.drive != "unknown":
            asserted["drive"] = row.drive
        if index is None:
            score.unmatched_rows += 1
            score.asserted += len(asserted)
            score.errors.append(f"{entry['doc_id']}: unexpected row {row.equipment_id}")
            if "drive" in asserted:
                score.wrong_drives.append(f"{entry['doc_id']}:{row.equipment_id}")
            continue
        used.add(index)
        score.matched_rows += 1
        exp = expected[index]
        truth = {
            "type": exp["type"],
            "rating": Decimal(exp["rating_value"]),
            "unit": exp["unit"],
            "count": exp["count"],
            "drive": exp["drive"],
        }
        for name, value in asserted.items():
            score.asserted += 1
            if truth[name] == value:
                score.correct += 1
            else:
                score.errors.append(
                    f"{entry['doc_id']}: {row.equipment_id} {name} {value!r} != {truth[name]!r}"
                )
                if name == "drive":
                    score.wrong_drives.append(f"{entry['doc_id']}:{row.equipment_id}")
        for name in ("type", "rating", "unit", "count", "drive"):
            if name in ("count", "drive") and truth[name] in (None, "unknown"):
                continue
            score.expected_fields += 1
            got = {"type": row.equipment_type, "rating": row.rating, "unit": row.unit}.get(name)
            if name == "count":
                got = row.count
            if name == "drive":
                got = row.drive
            score.recalled_fields += int(got == truth[name])
    for index, exp in enumerate(expected):
        if index not in used:
            score.expected_fields += sum(
                1
                for name in ("type", "rating_value", "unit", "count", "drive")
                if exp[name] not in (None, "unknown")
            )


@pytest.fixture(scope="module")
def gold_score() -> Score:
    score = Score()
    for entry in load_gold():
        score_entry(entry, score)
    return score


def test_gold_set_is_large_enough_and_well_formed() -> None:
    entries = load_gold()
    assert len(entries) >= MIN_DOCUMENTS
    ids = [e["doc_id"] for e in entries]
    assert len(ids) == len(set(ids))
    sources = " ".join(e["source"] for e in entries)
    for state_marker in ("Oklahoma", "NMED", "TCEQ"):
        assert state_marker in sources
    for entry in entries:
        assert len(entry["page_text_excerpt"]) < 3500
        for exp in entry["expected_rows"]:
            assert set(exp) == {"equipment_id", "type", "rating_value", "unit", "count", "drive"}
            assert exp["drive"] in {"electric", "gas_engine", "diesel_engine", "steam", "unknown"}
            Decimal(exp["rating_value"])


def test_gold_field_precision(gold_score: Score) -> None:
    precision = gold_score.correct / gold_score.asserted
    print(
        f"\ngold precision {precision:.4f} ({gold_score.correct}/{gold_score.asserted} asserted "
        f"fields; {gold_score.unmatched_rows} unexpected rows)"
    )
    assert gold_score.wrong_drives == [], gold_score.wrong_drives
    assert precision >= PRECISION_GATE, "\n".join(gold_score.errors)


def test_gold_recall_is_reported(gold_score: Score) -> None:
    recall = gold_score.recalled_fields / gold_score.expected_fields
    row_recall = gold_score.matched_rows / gold_score.expected_rows
    print(
        f"\ngold recall (informational): fields {recall:.3f} "
        f"({gold_score.recalled_fields}/{gold_score.expected_fields}), "
        f"rows {row_recall:.3f} ({gold_score.matched_rows}/{gold_score.expected_rows})"
    )
    assert recall >= RECALL_FLOOR
