const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = process.env.GRIDLENS_SOURCE_ROOT || path.resolve(__dirname, '../../../..');
const { chromium, expect } = require(path.join(root, 'web/node_modules/@playwright/test'));
const seed = JSON.parse(fs.readFileSync(process.env.GRIDLENS_SMOKE_MANIFEST || '/workspace/task-runtime/retained_ui_smoke_seed_replay.json', 'utf8'));
if (!seed.database_name?.endsWith('_test')) throw new Error('Smoke manifest must identify a disposable test database');
const output = process.env.GRIDLENS_SMOKE_OUTPUT || path.join(root, 'docs/validation/customer-intelligence-20261112/default-native-ui-replay');
const digest = file => crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
const files = ['web/src/features/workspace/ProjectResults.tsx', 'web/src/features/workspace/Workspace.tsx', 'web/src/features/workspace/CanonicalOpportunityDetail.tsx', 'web/src/features/companies/CompanyView.tsx', 'web/src/api/client.ts', 'web/src/state/projectBrowseCache.ts', 'backend/src/gridlens/intelligence/customer_results.py', 'backend/src/gridlens/api/app.py'];
let liveBrowser;
let livePage;
let phase = 'initial';
const pageErrors = [];
const hashes = () => Object.fromEntries(files.map(file => [file, digest(path.join(root, file))]));
(async () => {
  if (fs.existsSync(output)) throw new Error('Refusing to overwrite native UI receipt');
  fs.mkdirSync(output);
  const beforeHashes = hashes();
  const browser = await chromium.launch({ headless: true });
  liveBrowser = browser;
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
  const external = [];
  await context.route('**/*', route => {
    const url = new URL(route.request().url());
    if (['127.0.0.1', 'localhost', '[::1]'].includes(url.hostname)) return route.continue();
    external.push(url.origin + url.pathname);
    return route.abort();
  });
  const page = await context.newPage();
  livePage = page;
  page.on('pageerror', error => pageErrors.push(error.message));
  const groupResponses = [];
  page.on('response', async response => {
    const url = new URL(response.url());
    if (url.pathname !== '/api/opportunities/groups') return;
    groupResponses.push({ url: response.url(), status: response.status(), body: await response.json() });
  });
  phase = 'current-default';
  await page.goto('http://127.0.0.1:15491/');
  await page.getByLabel('Password', { exact: true }).fill(process.env.GRIDLENS_TEST_PASSWORD);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Customers', exact: true })).toBeVisible();
  await expect(page.locator('.customer-group')).toHaveCount(2);
  // Compare old and new frontend defaults against the same current backend/data.
  phase = 'baseline-default';
  await page.goto('http://127.0.0.1:15490/');
  await expect(page.getByRole('heading', { name: 'Customers', exact: true })).toBeVisible();
  await expect(page.getByRole('navigation', { name: 'Opportunity scope' }).getByRole('button', { name: 'Shortlist', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await expect(page.locator('.project-empty')).toBeVisible();
  await expect(page.locator('.customer-group')).toHaveCount(0);
  await page.screenshot({ path: path.join(output, 'before-default-desktop.png'), fullPage: true });
  phase = 'current-default';
  await page.goto('http://127.0.0.1:15491/');
  const all = page.getByRole('navigation', { name: 'Opportunity scope' }).getByRole('button', { name: 'All customers', exact: true });
  await expect(all).toHaveAttribute('aria-pressed', 'true');
  await expect(page.locator('.customer-group')).toHaveCount(2);
  await expect(page.locator('.customer-group').filter({ hasText: 'DataBank' })).toContainText('480 MW');
  await expect(page.locator('.customer-group').filter({ hasText: 'CyrusOne' })).toContainText('by fourth quarter of 2026');
  await page.screenshot({ path: path.join(output, 'after-default-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: path.join(output, 'after-default-mobile.png'), fullPage: true });
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.getByRole('navigation', { name: 'Opportunity scope' }).getByRole('button', { name: 'Shortlist', exact: true }).click();
  await expect(page.locator('.project-empty')).toBeVisible();
  await expect(page.locator('.customer-group')).toHaveCount(0);
  await all.click();
  await expect(page.locator('.customer-group')).toHaveCount(2);
  await page.locator('.customer-group').filter({ hasText: 'DataBank' }).getByRole('button', { name: /DataBank/ }).click();
  await expect(page.getByRole('heading', { name: 'DataBank', exact: true })).toBeVisible();
  expect(new URL(page.url()).searchParams.get('shortlist')).toBe('0');
  expect(new URL(page.url()).searchParams.get('customerScope')).toBe('canonical');
  await page.reload();
  await expect(page.getByRole('heading', { name: 'DataBank', exact: true })).toBeVisible();
  await expect(page.getByRole('region', { name: 'Account projects' })).toBeVisible();
  await page.screenshot({ path: path.join(output, 'after-databank-detail.png'), fullPage: true });
  const afterHashes = hashes();
  expect(afterHashes).toEqual(beforeHashes);
  expect(external).toEqual([]);
  const actualAll = groupResponses.filter(item => new URL(item.url).port === '15491' && new URL(item.url).searchParams.get('shortlist') === 'false');
  expect(actualAll.length).toBeGreaterThan(0);
  expect(actualAll.every(item => new URL(item.url).searchParams.get('canonical_only') === 'true')).toBe(true);
  expect(actualAll.every(item => item.body.total === 2 && item.body.items.every(group => group.group_kind === 'resolved_identity'))).toBe(true);
  const generationIds = [...new Set(groupResponses.map(item => item.body.generation_id))];
  expect(generationIds).toHaveLength(1);
  await browser.close();
  const screenshots = Object.fromEntries(fs.readdirSync(output).filter(file => file.endsWith('.png')).map(file => [file, digest(path.join(output, file))]));
  fs.writeFileSync(path.join(output, 'receipt.json'), JSON.stringify({ captured_at: new Date().toISOString(), database: seed.database_name, native_source_data: true, api_mocking: false, baseline_frontend_commit: '2cf4f67b', comparison_backend_source: beforeHashes, limitations: ['Same current backend and test database; before image compares frontend defaults, not a complete old backend deployment.', 'Only two admitted organizations; historical source announcements do not establish current project status or verified customer demand.', 'No salesperson usability acceptance or production performance measurement.'], groupResponses, generationIds, source_hashes: afterHashes, screenshots, external_requests: external }, null, 2));
  console.log('PASS: native default shows two canonical customers; old default and explicit Shortlist show zero; detail survives reload.');
})().catch(async error => { console.error(JSON.stringify({phase, url: livePage?.url(), pageErrors, body: await livePage?.locator('body').innerText().catch(() => ''), error: error.message})); await liveBrowser?.close(); process.exitCode = 1; });
